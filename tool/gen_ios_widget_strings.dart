// Generates the iOS String Catalogs used by the widget extension and the
// App Shortcuts provider, sourced from lib/l10n/app_*.arb.
//
// Why this exists: the widget extension and AppIntents are a *second*
// localization surface. `LocalizedStringResource` / `AppShortcut` phrases
// resolve through `.xcstrings` in their own target and cannot read the ARB
// catalogue. Rather than maintain 24 locales twice, this projects the relevant
// ARB keys into the two catalogs.
//
// Most *rendered* widget text is shipped pre-localized inside the snapshot
// JSON, so these catalogs stay small: configuration-sheet UI, Siri phrases,
// the widget-gallery entries, and the no-snapshot empty state (which must
// render before any snapshot exists).
//
// Run from the repo root:  dart run tool/gen_ios_widget_strings.dart


/// Compact-number suffixes have no ARB equivalent (they exist only in the
/// widget's circular accessory). Kept here rather than polluting the app's
/// catalogue with strings the app never shows.
const Map<String, Map<String, String>> _literals = {
  'unit.thousand': {'*': 'k'},
  'unit.million': {'*': 'M'},
};

/// Siri phrases. The `{appName}` placeholder in the ARB becomes the
/// `\${applicationName}` token the App Intents runtime substitutes.
const Map<String, String> _phraseKeys = {
  'Add a transaction in \${applicationName}': 'widgetSiriAddTransaction',
  'Add a planned transaction in \${applicationName}': 'widgetSiriAddPlanned',
};


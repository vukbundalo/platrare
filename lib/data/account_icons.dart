import 'package:flutter/material.dart';

/// The icons an account may use, as const `Icons.*` references.
///
/// Flutter's release builds tree-shake the Material icon font down to the
/// glyphs referenced by const [IconData]; a runtime
/// `IconData(codePoint, fontFamily: 'MaterialIcons')` is rejected at
/// bundling time. So stored code points are resolved back to these const
/// definitions with [accountIconForCodePoint], never constructed.

class AccountPickIconDef {
  const AccountPickIconDef(this.icon, this.materialName);
  final IconData icon;
  final String materialName;
}

String accountPickIconSearchHaystack(AccountPickIconDef d) {
  final spaced = d.materialName.replaceAll('_', ' ');
  return '${d.materialName} $spaced';
}

bool accountPickIconMatchesQuery(AccountPickIconDef d, String queryRaw) {
  final q = queryRaw.toLowerCase().trim();
  if (q.isEmpty) return true;
  final hay = accountPickIconSearchHaystack(d).toLowerCase();
  if (hay.contains(q)) return true;
  final parts =
      q.split(RegExp(r'\s+')).where((String s) => s.isNotEmpty).toList();
  if (parts.isEmpty) return true;
  for (final w in parts) {
    if (!hay.contains(w)) return false;
  }
  return true;
}

